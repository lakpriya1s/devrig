#!/usr/bin/env node
// Regenerates knowledge/index.md from the frontmatter of every doc in
// knowledge/. Run after adding/editing docs: `node scripts/build-knowledge-index.mjs`
// Requires Node 18+. No dependencies — parses only the flat scalar/list
// frontmatter shape used by the write-doc templates (see
// .agents/skills/write-doc/doc-style.md), not general YAML.

import { readdirSync, statSync, readFileSync, writeFileSync } from "node:fs";
import { join, relative, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const KNOWLEDGE_DIR = join(ROOT, "knowledge");

const SKIP_FILES = new Set(["README.md", "index.md", "0000-template.md"]);

function walk(dir) {
  const out = [];
  for (const entry of readdirSync(dir)) {
    const full = join(dir, entry);
    const st = statSync(full);
    if (st.isDirectory()) {
      out.push(...walk(full));
    } else if (entry.endsWith(".md") && !SKIP_FILES.has(entry)) {
      out.push(full);
    }
  }
  return out;
}

// Parses `key: value`, `key: [a, b, c]`, and quoted scalars. Good enough for
// the flat frontmatter schema in knowledge/README.md — not a general parser.
function parseFrontmatter(content) {
  const match = content.match(/^---\n([\s\S]*?)\n---/);
  if (!match) return null;
  const fm = {};
  for (const line of match[1].split("\n")) {
    const kv = line.match(/^([A-Za-z_]+):\s*(.*)$/);
    if (!kv) continue;
    const [, key, rawValue] = kv;
    let value = rawValue.trim();
    if (value.startsWith("[") && value.endsWith("]")) {
      value = value
        .slice(1, -1)
        .split(",")
        .map((s) => s.trim().replace(/^["']|["']$/g, ""))
        .filter(Boolean);
    } else {
      value = value.replace(/^["']|["']$/g, "");
      if (value === "true") value = true;
      else if (value === "false") value = false;
      else if (value === "null" || value === "") value = null;
    }
    fm[key] = value;
  }
  return fm;
}

const files = walk(KNOWLEDGE_DIR);
const docs = [];
for (const file of files) {
  const content = readFileSync(file, "utf8");
  const fm = parseFrontmatter(content);
  const relPath = relative(ROOT, file);
  if (!fm) {
    docs.push({ path: relPath, missingFrontmatter: true });
    continue;
  }
  docs.push({ path: relPath, ...fm });
}

function section(title, items, render) {
  if (items.length === 0) return `## ${title}\n\n_None yet._\n`;
  return `## ${title}\n\n${items.map(render).join("\n")}\n`;
}

const link = (d) => `- [${d.title || d.path}](${relative(KNOWLEDGE_DIR, join(ROOT, d.path))}) — ${d.status || "unknown status"}`;

const withFm = docs.filter((d) => !d.missingFrontmatter);
const missing = docs.filter((d) => d.missingFrontmatter);

const architecture = withFm.filter((d) => d.type === "architecture" && !["deprecated", "superseded", "archived"].includes(d.status));
const designs = withFm.filter((d) => d.type === "design" && ["draft", "proposed"].includes(d.status));
const decisions = withFm.filter((d) => d.type === "decision" && d.status === "accepted");
const runbooks = withFm.filter((d) => d.type === "runbook" && !["deprecated", "superseded", "archived"].includes(d.status));
const product = withFm.filter((d) => d.type === "product" && !["deprecated", "superseded", "archived"].includes(d.status));
const deprecated = withFm.filter((d) => ["deprecated", "superseded", "archived"].includes(d.status));

const recent = [...withFm]
  .filter((d) => d.last_reviewed || d.created)
  .sort((a, b) => (b.last_reviewed || b.created || "").localeCompare(a.last_reviewed || a.created || ""))
  .slice(0, 10);

const out = `# Knowledge Index

<!-- Generated by scripts/build-knowledge-index.mjs — do not edit by hand.
     Regenerate after adding/editing docs. -->

${section("Architecture", architecture, link)}
${section("Active Designs", designs, link)}
${section("Accepted Decisions", decisions, link)}
${section("Operational Runbooks", runbooks, link)}
${section("Product Knowledge", product, link)}
${section("Recently Reviewed", recent, link)}
${section("Deprecated / Superseded / Archived", deprecated, link)}
${missing.length > 0 ? `## Missing frontmatter\n\nThese docs have no frontmatter and are excluded from the sections above — add it (see \`knowledge/README.md\`):\n\n${missing.map((d) => `- ${d.path}`).join("\n")}\n` : ""}`;

writeFileSync(join(KNOWLEDGE_DIR, "index.md"), out);
console.log(`Wrote knowledge/index.md (${docs.length} docs, ${missing.length} missing frontmatter)`);
